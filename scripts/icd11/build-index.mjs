#!/usr/bin/env node
/**
 * Builds packages/interop/src/terminology/icd11-mms-data.ts from the WHO
 * ICD-11 MMS "Simple Tabulation" release file.
 *
 *   curl -LO https://icdcdn.who.int/static/releasefiles/2026-01/SimpleTabulation-ICD-11-MMS-en.zip
 *   unzip SimpleTabulation-ICD-11-MMS-en.zip -d /some/empty/dir
 *   node scripts/icd11/build-index.mjs /some/empty/dir/SimpleTabulation-ICD-11-MMS-en.txt 2026-01
 *
 * Kept: every coded category in chapters 01-25 (diagnoses, symptoms, external
 * causes, factors influencing health, COVID-19). Dropped: chapter 26
 * (traditional medicine, S codes), chapter V (functioning) and chapter X
 * (extension codes), none of which is a diagnosis.
 *
 * Titles, codes and foundation identifiers are copied exactly as WHO publishes
 * them; nothing is reworded. ICD-11 is (c) WHO, CC BY-ND 3.0 IGO.
 */
import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const [, , input, release] = process.argv
if (!input || !/^\d{4}-\d{2}$/.test(release ?? "")) {
  console.error("usage: node scripts/icd11/build-index.mjs <SimpleTabulation-ICD-11-MMS-en.txt> <release e.g. 2026-01>")
  process.exit(2)
}

const raw = readFileSync(input, "utf8").replace(/^﻿/, "")
const lines = raw.split(/\r?\n/)
const header = lines[0].split("\t")
const col = (name) => {
  const i = header.findIndex((h) => h.trim().toLowerCase() === name.toLowerCase())
  if (i < 0) throw new Error(`column ${name} missing from ${input}`)
  return i
}
const C = {
  foundation: col("Foundation URI"),
  code: col("Code"),
  title: col("Title"),
  kind: col("ClassKind"),
  chapter: col("ChapterNo"),
  leaf: col("isLeaf"),
  residual: col("IsResidual"),
  parent: col("Parent"),
}

const unquote = (s) => {
  let v = (s ?? "").trim()
  if (v.startsWith('"') && v.endsWith('"')) v = v.slice(1, -1).replace(/""/g, '"')
  return v
}
const foundationId = (uri) => {
  const m = /\/entity\/(\d+)$/.exec(unquote(uri))
  return m ? m[1] : ""
}

const rows = []
const codeByFoundation = new Map()
for (const line of lines.slice(1)) {
  if (!line.trim()) continue
  const f = line.split("\t")
  const id = foundationId(f[C.foundation])
  const code = unquote(f[C.code])
  if (id && code) codeByFoundation.set(id, code)
  if (unquote(f[C.kind]) !== "category" || !code) continue
  const chapter = unquote(f[C.chapter])
  if (!/^(0[1-9]|1\d|2[0-5])$/.test(chapter)) continue
  // The tabulation prefixes titles with "- " per depth level.
  const title = unquote(f[C.title]).replace(/^(?:-\s*)+/, "").trim()
  if (!title || /[\t\n]/.test(title)) throw new Error(`bad title for ${code}`)
  rows.push({
    code,
    title,
    id,
    chapter,
    leaf: unquote(f[C.leaf]).toLowerCase() === "true",
    residual: unquote(f[C.residual]).toLowerCase() === "true",
    parentId: foundationId(f[C.parent]),
  })
}

const seen = new Set()
for (const r of rows) {
  if (seen.has(r.code)) throw new Error(`duplicate code ${r.code}`)
  seen.add(r.code)
}
rows.sort((a, b) => a.code.localeCompare(b.code))

// code \t title \t foundationId \t parentCode \t flags(L=leaf,R=residual) \t chapter
const body = rows
  .map((r) => [r.code, r.title, r.id, codeByFoundation.get(r.parentId) ?? "", `${r.leaf ? "L" : ""}${r.residual ? "R" : ""}`, r.chapter].join("\t"))
  .join("\n")

const here = dirname(fileURLToPath(import.meta.url))
const out = join(here, "../../packages/interop/src/terminology/icd11-mms-data.ts")
writeFileSync(
  out,
  `/* eslint-disable */\n// GENERATED by scripts/icd11/build-index.mjs from the WHO ICD-11 MMS ${release}\n` +
    `// Simple Tabulation. Do not edit by hand. ICD-11 (c) World Health Organization,\n` +
    `// licensed CC BY-ND 3.0 IGO: codes and titles are reproduced unaltered.\n` +
    `// Columns: code, title, foundation id, parent code, flags (L leaf, R residual), chapter.\n` +
    `export const ICD11_MMS_DATA_RELEASE = ${JSON.stringify(release)}\n` +
    `export const ICD11_MMS_DATA_COUNT = ${rows.length}\n` +
    `export const ICD11_MMS_TSV = ${JSON.stringify(body)}\n`,
)
console.log(`[icd11] ${rows.length} categories -> ${out}`)
