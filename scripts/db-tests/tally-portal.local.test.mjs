/**
 * The Tally replay journey through the real portal, against the disposable
 * stack that run-pharmacy-portal-harness.sh provisions.
 *
 * It seeds one synthetic pharmacy tenant and one administrator through the
 * service role, signs in through the real login form, uploads the synthetic
 * full-history export, confirms the sequence, applies the cut-over, and then
 * asks the profit report for the period the export covers. What the report
 * answers is the point of the journey: the two sales must be there, and each
 * must be costed at the purchase rate of the batch the replay says it moved,
 * not at a product cost that did not exist in the period.
 *
 * It then trades on the migrated data through the portal's own APIs — a
 * purchase, a sale, a refund and a manual stock adjustment — which is what
 * AC-9 means by independence: nothing after the cut-over may need Tally.
 *
 * Every value here is invented. The seeded credentials are generated by the
 * harness for one run and the stack is destroyed afterwards; nothing in this
 * file can reach a remote project because the harness refuses a non-loopback
 * API URL before it starts.
 */

import test from "node:test"
import assert from "node:assert/strict"
import { randomUUID } from "node:crypto"
import { existsSync } from "node:fs"
import { tmpdir } from "node:os"
import { join } from "node:path"
import bcrypt from "bcryptjs"
import { chromium } from "playwright-core"
import {
  FULL_HISTORY_COMPANY,
  FULL_HISTORY_PERIOD,
  buildFullHistoryXml,
} from "../../apps/pharmacy/lib/tally/full-history-fixture.ts"

const BASE = (process.env.PORTAL_BASE_URL ?? "").replace(/\/$/, "")
const API = (process.env.LOCAL_API_URL ?? "").replace(/\/$/, "")
const SERVICE_KEY = process.env.LOCAL_SERVICE_ROLE_KEY ?? ""
const EMAIL = process.env.PORTAL_EMAIL ?? ""
const PASSWORD = process.env.PORTAL_PASSWORD ?? ""

const missing = Object.entries({
  PORTAL_BASE_URL: BASE,
  LOCAL_API_URL: API,
  LOCAL_SERVICE_ROLE_KEY: SERVICE_KEY,
  PORTAL_EMAIL: EMAIL,
  PORTAL_PASSWORD: PASSWORD,
})
  .filter(([, value]) => !value)
  .map(([name]) => name)

const skip = missing.length
  ? `only runs under run-pharmacy-portal-harness.sh (missing ${missing.join(", ")})`
  : false

const CHROME = process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE
  || (existsSync("/usr/bin/google-chrome") ? "/usr/bin/google-chrome" : undefined)

const restHeaders = {
  apikey: SERVICE_KEY,
  Authorization: `Bearer ${SERVICE_KEY}`,
  "Content-Type": "application/json",
  Prefer: "return=representation",
}

async function insert(table, row) {
  const response = await fetch(`${API}/rest/v1/${table}`, {
    method: "POST",
    headers: restHeaders,
    body: JSON.stringify(row),
  })
  const text = await response.text()
  if (!response.ok) {
    throw new Error(`seeding ${table} failed: ${response.status} ${text}`)
  }
  return text ? JSON.parse(text) : []
}

async function seedAdministrator() {
  const tenantId = randomUUID()
  const profileId = randomUUID()
  const passwordHash = await bcrypt.hash(PASSWORD, 12)

  await insert("tenants", {
    id: tenantId,
    slug: `portal-acceptance-${tenantId.slice(0, 8)}`,
    name: "Synthetic Acceptance Pharmacy",
    facility_type: "pharmacy",
    status: "active",
    is_active: true,
    is_synthetic: true,
  })

  await insert("profiles", {
    id: profileId,
    tenant_id: tenantId,
    email: EMAIL,
    full_name: "Synthetic Acceptance Admin",
    role: "pharmacy_store_manager",
    is_admin: true,
    password_hash: passwordHash,
    email_verified_at: new Date().toISOString(),
    verification_status: "verified",
    onboarding_complete: true,
    must_change_password: false,
    is_deleted: false,
  })

  await insert("pharmacy_user_settings", {
    tenant_id: tenantId,
    profile_id: profileId,
    pharmacy_role: "pharmacy_store_manager",
    permissions: [],
    is_active: true,
    must_change_password: false,
    two_factor_enabled: false,
  })

  await insert("pharmacy_profiles", {
    tenant_id: tenantId,
    pharmacy_name: "Synthetic Acceptance Pharmacy",
  })

  // The till refuses to sell without an entitlement, and this tenant has no
  // billing history. An override is the product's own way to grant one.
  await insert("tenant_feature_overrides", {
    tenant_id: tenantId,
    feature_key: "pos.sell",
    enabled: true,
    reason: "Synthetic acceptance journey",
  })

  return { tenantId, profileId }
}

async function readSeededProfile() {
  const response = await fetch(
    `${API}/rest/v1/profiles?select=id,email,role,is_admin,password_hash,verification_status,must_change_password&email=eq.${encodeURIComponent(EMAIL)}`,
    { headers: restHeaders },
  )
  const text = await response.text()
  if (!response.ok) throw new Error(`reading the seeded profile failed: ${response.status} ${text}`)
  return JSON.parse(text)
}

async function readRest(path) {
  const response = await fetch(`${API}/rest/v1/${path}`, { headers: restHeaders })
  const text = await response.text()
  if (!response.ok) throw new Error(`reading ${path} failed: ${response.status} ${text}`)
  return JSON.parse(text)
}

async function updateRest(path, patch) {
  const response = await fetch(`${API}/rest/v1/${path}`, {
    method: "PATCH",
    headers: restHeaders,
    body: JSON.stringify(patch),
  })
  const text = await response.text()
  if (!response.ok) throw new Error(`updating ${path} failed: ${response.status} ${text}`)
  return text ? JSON.parse(text) : []
}

async function postAsSession(page, path, body) {
  return page.evaluate(
    async ({ path, body }) => {
      const response = await fetch(path, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify(body),
      })
      const text = await response.text()
      let parsed = null
      try {
        parsed = text ? JSON.parse(text) : null
      } catch {
        parsed = { raw: text }
      }
      return { status: response.status, body: parsed }
    },
    { path, body },
  )
}

async function profitReport(page, period) {
  const url =
    `/api/admin/reports?type=profit&period=custom` +
    `&startDate=${period.from}&endDate=${period.to}`
  const answer = await page.evaluate(async (path) => {
    const response = await fetch(path, { cache: "no-store" })
    const body = await response.json().catch(() => null)
    return { status: response.status, body }
  }, url)
  return answer
}

test(
  "the portal replays a Tally export and the profit report costs each sale at the batch rate it moved at",
  { skip, timeout: 600_000 },
  async (t) => {
    const seeded = await seedAdministrator()

    const browser = await chromium.launch({ headless: true, executablePath: CHROME })
    const page = await browser.newPage()
    const problems = []
    page.on("pageerror", (error) => problems.push(`pageerror: ${error.message}`))
    page.on("console", (message) => {
      if (message.type() === "error") problems.push(`console: ${message.text()}`)
    })
    // AC-9's sixth step, made observable: once the history is in, nothing on
    // screen may reach for a service outside this app and its own database.
    // No Tally bridge is configured here, so a request that leaves those two
    // origins is a hidden dependency, whatever it was trying to call.
    const foreign = []
    page.on("request", (request) => {
      const url = request.url()
      if (url.startsWith("data:") || url.startsWith("blob:") || url.startsWith("chrome-extension:")) {
        return
      }
      const origin = new URL(url).origin
      if (origin === new URL(BASE).origin) return
      if (API && origin === new URL(API).origin) return
      foreign.push(url)
    })

    t.after(async () => {
      try {
        await page.screenshot({ path: join(tmpdir(), "tally-portal-journey.png"), fullPage: true })
      } catch {
        // The page may already be closed; the assertions below already spoke.
      }
      await browser.close()
    })

    await t.test("signs in through the login form", async () => {
      const [profile] = await readSeededProfile()
      assert.ok(profile, `no profile row is readable for ${EMAIL}`)
      assert.ok(profile.password_hash, "the seeded profile carries no password_hash")
      assert.equal(
        await bcrypt.compare(PASSWORD, profile.password_hash),
        true,
        "the seeded hash does not verify against the password the form will submit",
      )

      await page.goto(`${BASE}/login`, { waitUntil: "domcontentloaded" })
      // The form is a client component. Clicking before React attaches its
      // submit handler posts the form natively, which reloads /login and never
      // reaches the API; React marks a node it owns with an internal property
      // once hydration has run.
      await page.waitForFunction(
        () => {
          const form = document.querySelector("form")
          return Boolean(form) && Object.keys(form).some((key) => key.startsWith("__reactFiber$"))
        },
        null,
        { timeout: 120_000 },
      )
      await page.fill("#identifier", EMAIL)
      await page.fill("#password", PASSWORD)
      const answer = page.waitForResponse(
        (response) => response.url().endsWith("/api/auth/login") && response.request().method() === "POST",
        { timeout: 120_000 },
      )
      await page.getByRole("button", { name: "Sign in" }).click()
      const response = await answer
      if (!response.ok()) {
        assert.fail(`the login API answered ${response.status()}: ${await response.text()}`)
      }
      await page.waitForURL(/\/portal\//, { timeout: 60_000 })
    })

    await t.test("uploads the export in replay mode and reads it", async () => {
      await page.goto(`${BASE}/portal/tally-import`, { waitUntil: "domcontentloaded" })
      await page.getByRole("button", { name: "Full history — replay" }).click()

      const xml = buildFullHistoryXml()
      assert.match(xml, new RegExp(FULL_HISTORY_COMPANY.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")))

      await page.setInputFiles("#tally-file", {
        name: `full-history-${FULL_HISTORY_PERIOD.from.replaceAll("-", "")}-${FULL_HISTORY_PERIOD.to.replaceAll("-", "")}.xml`,
        mimeType: "application/xml",
        buffer: Buffer.from(xml),
      })
      await page.getByRole("button", { name: "Upload and review" }).click()

      // The sequence card only renders once the server has read the export and
      // simulated the replay; it is the portal's "review is ready" signal.
      await page.locator("#tally-replay-sequence").waitFor({ state: "visible", timeout: 180_000 })
    })

    await t.test("has no unanswered replay difference in the synthetic export", async () => {
      // Reading the card's text alone cannot tell "no differences" from "the
      // gate was never loaded", so ask the session what it holds.
      const gate = await page.evaluate(async () => {
        const id = window.localStorage.getItem("tallySessionId")
        const response = await fetch(`/api/admin/tally/${id}`)
        const data = await response.json()
        return {
          mode: data.summary?.mode ?? null,
          replay: data.replay
            ? {
                canApply: data.replay.canApply,
                blockers: data.replay.blockers,
                missing: data.replay.missing,
              }
            : null,
          preflight: data.cutoverPreflight ?? null,
          blocking: (data.summary?.exceptions ?? []).filter(
            (entry) => entry.severity === "blocking",
          ),
          opening: data.summary?.opening ?? null,
        }
      })
      assert.equal(gate.mode, "replay", "the uploaded export must be read in replay mode")
      assert.ok(gate.replay, "the session carries no replay gate for a replay-mode plan")
      assert.deepEqual(gate.replay.blockers, [], "the synthetic export produced replay differences")
      assert.deepEqual(gate.blocking, [], "the synthetic export produced blocking exceptions")
    })

    await t.test("confirms the sequence and applies the cut-over", async () => {
      const unverified = page.locator("#tally-unverified-ack")
      if (await unverified.count()) await unverified.check()

      await page.locator("#tally-replay-sequence").check()

      const applyButton = page.getByRole("button", { name: "Apply cut-over" })
      await applyButton.waitFor({ state: "visible", timeout: 60_000 })
      if (!(await applyButton.isEnabled())) {
        const why = await page.evaluate(async () => {
          const id = window.localStorage.getItem("tallySessionId")
          const response = await fetch(`/api/admin/tally/${id}`)
          const data = await response.json()
          return {
            mode: data.summary?.mode ?? null,
            opening: data.summary?.opening ?? null,
            blocking: (data.summary?.exceptions ?? []).filter(
              (entry) => entry.severity === "blocking",
            ),
            replay: data.replay
              ? {
                  canApply: data.replay.canApply,
                  sequenceConfirmed: data.replay.sequenceConfirmed,
                  blockers: data.replay.blockers,
                  missing: data.replay.missing,
                  unknown: data.replay.unknown,
                }
              : null,
            preflight: data.cutoverPreflight ?? null,
            unverified: Boolean(data.unverifiedAcknowledged),
            status: data.status ?? null,
          }
        })
        assert.fail(`the portal keeps Apply disabled: ${JSON.stringify(why, null, 2)}`)
      }
      const answered = page.waitForResponse(
        (response) =>
          /\/api\/admin\/tally\/[^/]+\/apply$/.test(response.url()) &&
          response.request().method() === "POST",
        { timeout: 180_000 },
      )
      await applyButton.click({ timeout: 180_000 })
      const applyAnswer = await answered
      if (!applyAnswer.ok()) {
        assert.fail(
          `the apply answered ${applyAnswer.status()}: ${await applyAnswer.text()}`,
        )
      }

      await page
        .getByText(/Tally cut-over is already complete for this pharmacy/)
        .waitFor({ timeout: 300_000 })
    })

    await t.test("a second apply answers done without touching the history", async () => {
      const again = await page.evaluate(async () => {
        const sessionId = window.localStorage.getItem("tallySessionId")
        if (!sessionId) return { skipped: "the portal kept no session id" }
        const response = await fetch(`/api/admin/tally/${sessionId}/apply`, {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify({
            acknowledgeUnverified: true,
            acknowledgeReplay: { sequenceConfirmed: true, items: [] },
          }),
        })
        return { status: response.status, body: await response.json().catch(() => null) }
      })
      if (again.skipped) return
      assert.equal(again.status, 200, `a repeat apply answered ${again.status}`)
      assert.equal(again.body?.done, true)
      assert.equal(again.body?.alreadyComplete, true)
    })

    await t.test("reports two sales at their historical cost", async () => {
      const { status, body } = await profitReport(page, FULL_HISTORY_PERIOD)
      assert.equal(status, 200, `profit report answered ${status}`)
      assert.equal(body?.type, "profit")

      assert.equal(body.summary.transactionCount, 2, "both mirrored sales must be in the period")
      assert.equal(body.summary.totalRevenue, 49_000)
      // Amoxicillin 30 units out of the 500/unit batch expiring first, and
      // Paracetamol 50 units out of the 300/unit purchase: 15,000 each.
      assert.equal(body.summary.totalCost, 30_000)
      assert.equal(body.summary.grossProfit, 19_000)

      const products = Object.fromEntries(
        (body.profitByProduct ?? []).map((row) => [row.name, row]),
      )
      assert.equal(products["Amoxicillin 250mg"]?.cost, 15_000)
      assert.equal(products["Paracetamol 500mg"]?.cost, 15_000)
    })

    await t.test("renders the migrated period's report on screen", async () => {
      // AC-9 step 5 is about the screen, not the API: the report has to draw
      // for a period that only the replay ever wrote to.
      await page.goto(`${BASE}/portal/reports`, { waitUntil: "domcontentloaded" })
      await page.getByRole("button", { name: "Profit", exact: true }).click()
      await page.getByRole("button", { name: "Custom Range", exact: true }).click()

      const dates = page.locator('input[type="date"]')
      await dates.nth(0).fill(FULL_HISTORY_PERIOD.from)
      await dates.nth(1).fill(FULL_HISTORY_PERIOD.to)
      await page.getByRole("button", { name: "Apply", exact: true }).click()

      const grossProfit = page.locator("text=Gross Profit").first()
      await grossProfit.waitFor({ state: "visible", timeout: 60_000 })
      // The card formats through Intl for en-UG, whose symbol for UGX is "USh".
      await page.getByText("USh 19,000", { exact: true }).first().waitFor({ timeout: 60_000 })
    })

    await t.test("records a purchase and raises stock without Tally", async () => {
      const [supplier] = await insert("pharmacy_suppliers", {
        tenant_id: seeded.tenantId,
        name: "Synthetic Wholesaler",
        is_active: true,
      })
      const [product] = await readRest(
        `pharmacy_products?select=id,name,quantity&tenant_id=eq.${seeded.tenantId}&name=eq.${encodeURIComponent("Amoxicillin 250mg")}`,
      )
      assert.ok(product, "the replay must have created Amoxicillin 250mg")

      const answer = await postAsSession(page, "/api/admin/purchases", {
        supplierId: supplier.id,
        paymentMethod: "cash",
        amountPaid: 0,
        receiveNow: true,
        lines: [
          {
            productId: product.id,
            productName: product.name,
            quantity: 10,
            unitCost: 400,
            batchNumber: "AC-TEST-01",
            expiryDate: "2027-06-30",
            sellingPrice: 500,
          },
        ],
      })
      assert.equal(
        answer.status,
        200,
        `the purchase answered ${answer.status}: ${JSON.stringify(answer.body)}`,
      )
      assert.equal(answer.body?.ok, true)

      const [after] = await readRest(`pharmacy_products?select=id,quantity&id=eq.${product.id}`)
      assert.equal(Number(after.quantity), Number(product.quantity) + 10)
    })

    await t.test("completes a sale at the till without Tally", async () => {
      const [product] = await readRest(
        `pharmacy_products?select=id,name,quantity&tenant_id=eq.${seeded.tenantId}&name=eq.${encodeURIComponent("Amoxicillin 250mg")}`,
      )
      const before = Number(product.quantity)

      // Tally exports cost, never a selling price, so the operator prices the
      // imported product before the till may charge for it.
      await updateRest(`pharmacy_products?id=eq.${product.id}`, { price: 800 })

      const answer = await postAsSession(page, "/api/admin/pos/complete-sale", {
        items: [{ productId: product.id, quantity: 1 }],
        paymentMethod: "cash",
      })
      assert.equal(
        answer.status,
        200,
        `the sale answered ${answer.status}: ${JSON.stringify(answer.body)}`,
      )
      assert.equal(answer.body?.ok, true)
      assert.ok(answer.body?.sale?.sale_id, "the sale must name the row it wrote")

      const [after] = await readRest(`pharmacy_products?select=id,quantity&id=eq.${product.id}`)
      assert.equal(Number(after.quantity), before - 1)
    })

    await t.test("refunds that sale", async () => {
      const [sale] = await readRest(
        `pharmacy_pos_sales?select=id,receipt_number,status&tenant_id=eq.${seeded.tenantId}&order=created_at.desc&limit=1`,
      )
      assert.ok(sale, "the till must have written a sale")

      const answer = await postAsSession(page, "/api/admin/refunds", {
        transactionId: sale.id,
        reason: "Acceptance journey refund",
        restoreAs: "active",
      })
      assert.equal(
        answer.status,
        200,
        `the refund answered ${answer.status}: ${JSON.stringify(answer.body)}`,
      )
      assert.equal(answer.body?.success, true)
      assert.ok(Number(answer.body?.refundAmount) > 0, "the refund must hand money back")
    })

    await t.test("adjusts stock by hand", async () => {
      const [product] = await readRest(
        `pharmacy_products?select=id,name,quantity&tenant_id=eq.${seeded.tenantId}&name=eq.${encodeURIComponent("Amoxicillin 250mg")}`,
      )
      const before = Number(product.quantity)

      const answer = await postAsSession(page, "/api/admin/inventory/stock", {
        productId: product.id,
        quantity: 5,
        type: "INCREASE",
        reason: "Acceptance journey adjustment",
        batchNumber: "AC-ADJ-01",
        expiryDate: "2027-12-31",
        costPrice: 400,
        sellingPrice: 500,
      })
      assert.equal(
        answer.status,
        200,
        `the adjustment answered ${answer.status}: ${JSON.stringify(answer.body)}`,
      )
      assert.equal(answer.body?.product?.quantity, before + 5)

      const [after] = await readRest(`pharmacy_products?select=id,quantity&id=eq.${product.id}`)
      assert.equal(Number(after.quantity), before + 5)
    })

    await t.test("reports no error of its own during the journey", async () => {
      // Next.js dev logs a hydration warning as an error in some builds; only
      // failures the browser itself raised count here.
      const fatal = problems.filter((entry) => !entry.includes("Hydration failed"))
      assert.deepEqual(fatal, [])
    })

    await t.test("reaches nothing but this app and its own database", async () => {
      const outside = [...new Set(foreign)]
      assert.deepEqual(
        outside,
        [],
        `the journey called services outside the app and its database: ${outside.join(", ")}`,
      )
    })
  },
)
